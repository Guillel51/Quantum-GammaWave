  var ATTRS = ["alt", "aria-label", "title", "placeholder"];
  var textNodes = null, attrNodes = null, current = "en";
  var LANGS = ["en", "es", "zh"];
  var TITLE = document.title;
  var DESC = document.querySelector('meta[name="description"]');
  var DESC_TEXT = DESC ? DESC.getAttribute("content") : "";

  function snapshot() {
    textNodes = [];
    attrNodes = [];
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode;
        if (!p || /^(SCRIPT|STYLE|NOSCRIPT)$/.test(p.tagName)) return NodeFilter.FILTER_REJECT;
        return n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    var n;
    while ((n = walker.nextNode())) textNodes.push({ node: n, source: n.nodeValue });
    document.querySelectorAll("[alt],[aria-label],[title],[placeholder]").forEach(function (el) {
      ATTRS.forEach(function (a) {
        if (el.hasAttribute(a)) attrNodes.push({ el: el, attr: a, source: el.getAttribute(a) });
      });
    });
  }

  function mapFor(lang) { return lang === "en" || lang === "zh" ? TEXT[lang] : null; }

  function apply(lang) {
    if (LANGS.indexOf(lang) < 0) lang = "en";
    if (!textNodes) snapshot();
    current = lang;
    document.documentElement.lang = lang;
    var dict = mapFor(lang);
    document.title = (dict && dict[TITLE]) || TITLE;
    if (DESC) DESC.setAttribute("content", (dict && dict[DESC_TEXT]) || DESC_TEXT);
    textNodes.forEach(function (item) {
      var source = item.source, key = source.trim(), value = dict && dict[key];
      item.node.nodeValue = value ? source.replace(key, value) : source;
    });
    attrNodes.forEach(function (item) {
      var value = dict && dict[item.source];
      item.el.setAttribute(item.attr, value || item.source);
    });
  }

  function tr(source) {
    var dict = mapFor(current);
    return (dict && dict[source]) || source;
  }

  function missing(lang) {
    if (!textNodes) snapshot();
    var dict = mapFor(lang) || {}, out = [];
    textNodes.forEach(function (item) {
      var key = item.source.trim();
      if (/^(https?:|\/|#)/.test(key)) return;
      if (/[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]/.test(key) && !dict[key]) out.push(key);
    });
    attrNodes.forEach(function (item) {
      if (/^(https?:|\/|#)/.test(item.source)) return;
      if (/[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]/.test(item.source) && !dict[item.source]) out.push(item.source);
    });
    return Array.from(new Set(out));
  }

  window.QG_I18N = { apply: apply, tr: tr, missing: missing, languages: LANGS, current: function () { return current; } };
