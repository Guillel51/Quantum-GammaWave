#!/usr/bin/env python3
"""The hub card: what fmhub.json must say, and what stops it being weakened again.

The Firmware Hub reads `fmhub.json` from the default branch and drops the whole file when a field is
unknown or out of bounds, so a card that loses its `sounds` line is not a cosmetic failure: the listing
stops on it (it did, on 13.11.2026, because `web/banks/gw1-keys.syx` was in the tree and nothing said
where it came from). This test keeps both halves honest:

  1. the committed card passes every rule the hub publishes, including `sounds`;
  2. the tree's audio assets are all covered by that `sounds` line -- and removing the line fails, which
     is the regression the guard exists for;
  3. the validator accepts the four declarations the hub accepts and refuses a link, since a card is
     plain text and the hub says so.

Every check runs offline (`--offline`): this is a repository test, not a network probe.
"""
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHECK = ROOT / "tools" / "check_fmhub.py"
CARD = ROOT / "fmhub.json"


def run(path):
    r = subprocess.run([sys.executable, str(CHECK), str(path), "--offline"],
                       capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr


def main():
    bad = []
    ok = []

    code, out = run(CARD)
    (ok if code == 0 else bad).append(("the committed card passes every published rule", out.strip().splitlines()[-1]))

    card = json.loads(CARD.read_text(encoding="utf-8"))
    sounds = card.get("sounds")
    (ok if isinstance(sounds, str) and sounds.strip() else bad).append(
        ("the card declares where its sounds come from", repr(sounds)[:70]))

    # 2. the regression: with the sounds line gone, the card must not pass
    if sounds:
        with tempfile.TemporaryDirectory() as tmp:
            stripped = Path(tmp) / "fmhub.json"
            copy = {k: v for k, v in card.items() if k != "sounds"}
            stripped.write_text(json.dumps(copy, ensure_ascii=False, indent=2), encoding="utf-8")
            code, out = run(stripped)
            (ok if code != 0 and "sounds" in out else bad).append(
                ("a card that drops sounds is refused while the tree carries an audio asset", out.strip().splitlines()[-1]))

    # 3. the four declarations the hub accepts, and the one it does not
    good = ["none", "own", "own: the firmware synthesises every voice",
            "CC0: generated by tools/gen_fm6_patches.py",
            "public domain: the project's own FM6 bank",
            "licensed: JIANT FM, GPL-3.0-only"]
    bad_ones = ["own: see https://example.org for details", "our own sounds, honest",
                "licensed", "", "own: <html>"]
    sys.path.insert(0, str(ROOT / "tools"))
    import check_fmhub                                    # noqa: E402  (the rules under test)
    for text in good:
        (ok if any(r.match(text.lower()) for r in check_fmhub.SOUNDS_RULES)
         and not check_fmhub.NOT_TEXT.search(text) else bad).append((f"sounds accepted: {text!r}", ""))
    for text in bad_ones:
        rejected = not (any(r.match(text.lower()) for r in check_fmhub.SOUNDS_RULES)
                        and not check_fmhub.NOT_TEXT.search(text))
        (ok if rejected else bad).append((f"sounds refused: {text!r}", ""))

    for msg, _ in ok:
        print(f"ok    {msg}")
    for msg, detail in bad:
        print(f"FAIL  {msg}" + (f"  [{detail}]" if detail else ""))
    print(f"\nfmhub card: {len(ok)} held, {len(bad)} failed")
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
