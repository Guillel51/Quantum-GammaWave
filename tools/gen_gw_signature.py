#!/usr/bin/env python3
"""Generate firmware/src/ui_signature.h with the GAMMAWAVE FM-1 vector stroke power-on signature."""
import math
from pathlib import Path

SIG_W = 220
SIG_H = 112

def subdivide_stroke(pts, step=4.0):
    """Subdivide polyline points so Catmull-Rom + 5-tap smoothing in ui_draw.c renders crisp strokes."""
    out = []
    for i in range(len(pts) - 1):
        x0, y0 = pts[i]
        x1, y1 = pts[i + 1]
        dist = math.hypot(x1 - x0, y1 - y0)
        n = max(2, int(math.ceil(dist / step)))
        for k in range(n):
            t = k / n
            out.append((int(round(x0 + (x1 - x0) * t)), int(round(y0 + (y1 - y0) * t))))
    out.append((int(round(pts[-1][0])), int(round(pts[-1][1]))))
    # Remove consecutive duplicates
    clean = [out[0]]
    for p in out[1:]:
        if p != clean[-1]:
            clean.append(p)
    return clean

def make_strokes():
    strokes = []

    # 1. Top row: "GAMMA" (y = 12..46, bold stylized synth calligraphy)
    # G (x = 18..46)
    strokes.append(subdivide_stroke([(45, 16), (38, 12), (24, 12), (18, 20), (18, 38), (24, 46), (40, 46), (45, 38), (45, 29), (33, 29)]))
    # A (x = 54..80)
    strokes.append(subdivide_stroke([(54, 46), (67, 12), (80, 46)]))
    strokes.append(subdivide_stroke([(59, 34), (75, 34)]))
    # M (x = 88..122)
    strokes.append(subdivide_stroke([(88, 46), (90, 12), (105, 34), (120, 12), (122, 46)]))
    # M (x = 130..164)
    strokes.append(subdivide_stroke([(130, 46), (132, 12), (147, 34), (162, 12), (164, 46)]))
    # A (x = 172..202)
    strokes.append(subdivide_stroke([(172, 46), (187, 12), (202, 46)]))
    strokes.append(subdivide_stroke([(177, 34), (197, 34)]))

    # 2. Center Gamma Wave packet (y around 62, x = 10..210): high-energy FM wave packet
    wave_pts = []
    for i in range(65):
        u = i / 64.0
        x = 10 + u * 200.0
        env = math.sin(u * math.pi) ** 1.35
        carrier = math.sin(u * math.pi * 10.0 + 0.6 * math.sin(u * math.pi * 4.0))
        y = 62.0 - env * carrier * 13.5
        wave_pts.append((int(round(x)), int(round(y))))
    strokes.append(wave_pts)

    # 3. Bottom row: "WAVE  FM-1" (y = 80..104)
    # W (x = 20..46)
    strokes.append(subdivide_stroke([(20, 80), (26, 104), (33, 86), (40, 104), (46, 80)]))
    # A (x = 52..70)
    strokes.append(subdivide_stroke([(52, 104), (61, 80), (70, 104)]))
    strokes.append(subdivide_stroke([(55, 95), (67, 95)]))
    # V (x = 76..94)
    strokes.append(subdivide_stroke([(76, 80), (85, 104), (94, 80)]))
    # E (x = 100..116)
    strokes.append(subdivide_stroke([(116, 80), (100, 80), (100, 104), (116, 104)]))
    strokes.append(subdivide_stroke([(100, 92), (112, 92)]))

    # F (x = 134..148)
    strokes.append(subdivide_stroke([(148, 80), (134, 80), (134, 104)]))
    strokes.append(subdivide_stroke([(134, 92), (145, 92)]))
    # M (x = 154..176)
    strokes.append(subdivide_stroke([(154, 104), (155, 80), (165, 95), (175, 80), (176, 104)]))
    # - (x = 182..190)
    strokes.append(subdivide_stroke([(182, 92), (190, 92)]))
    # 1 (x = 196..204)
    strokes.append(subdivide_stroke([(195, 85), (200, 80), (200, 104)]))

    return strokes

def main():
    strokes = make_strokes()
    flat = []
    for s in strokes:
        if len(s) < 2:
            continue
        for idx, (x, y) in enumerate(s):
            x = max(0, min(SIG_W - 1, x))
            y = max(0, min(127, y))
            yb = (y | 128) if idx == 0 else y
            flat.extend([x, yb])
    sig_n = len(flat) // 2
    lines = [
        "/* generated by tools/gen_gw_signature.py: the GAMMAWAVE FM-1 power-on vector signature */",
        "#pragma once",
        f"#define SIG_W {SIG_W}",
        f"#define SIG_H {SIG_H}",
        f"#define SIG_N {sig_n}",
        "static const uint8_t SIG_PTS[SIG_N * 2] = {",
    ]
    for i in range(0, len(flat), 16):
        chunk = ", ".join(str(v) for v in flat[i:i+16])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")
    out_path = Path(__file__).resolve().parent.parent / "firmware" / "src" / "ui_signature.h"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({len(strokes)} strokes, {sig_n} points)")

if __name__ == "__main__":
    main()
