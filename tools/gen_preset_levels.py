"""Turn measured preset loudness into the level each preset loads with.

`tests/preset_levels` renders every factory preset once and prints its RMS. This reads that
measurement, works out the level that puts each sound on the bank's median, and writes
`firmware/src/preset_level.c`, which `ui.c` and `hostsim.c` apply when a sound is loaded.

    gcc -O2 -w -Ibuild/gen -Ifirmware/src -o build/preset_levels tests/preset_levels.c -lm
    build/preset_levels --csv > build/preset_levels.csv
    python3 tools/gen_preset_levels.py build/preset_levels.csv

The gain a level gives comes from LEVEL_Q12 in build/gen/felucca_tables.h, the same table the mixer
multiplies by: the search below only picks indices, so what it writes is exactly what the device does.
A sound quieter than the level can reach (the fader tops out ~13.5 dB over 100) keeps its maximum and
is listed, so the next pass is a change of the sound, not of the number.
"""
import csv
import re
import sys

ROOT = "."


def level_table():
    src = open("build/gen/felucca_tables.h", encoding="utf-8").read()
    m = re.search(r"LEVEL_Q12\[128\] = \{(.*?)\};", src, re.S)
    return [int(x) for x in re.findall(r"\d+", m.group(1))]


def current_levels():
    """The levels the tree already has, so a second pass corrects them instead of starting from 100:
    the measurement was taken WITH them applied, and starting again from the fader's own would count
    the correction twice (it did: the second pass made the spread worse, 34 -> 52)."""
    try:
        src = open("firmware/src/preset_level.c", encoding="utf-8").read()
    except OSError:
        return {}
    out = {}
    for m in re.finditer(r"static const uint8_t (LV_[A-Z0-9_]+)\[\d+\] = \{(.*?)\};", src, re.S):
        out[m.group(1)] = [int(x) for x in re.findall(r"\d+", m.group(2))]
    return out


def eng_array_name(name):
    return "LV_" + re.sub(r"[^A-Z0-9]", "_", name.upper())


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    lv = level_table()
    rows = []
    with open(argv[1], encoding="utf-8") as f:
        for r in csv.reader(f):
            if len(r) < 6:
                continue
            rows.append((int(r[0]), int(r[1]), r[2], r[3], float(r[4]), float(r[5])))
    if not rows:
        print("gen_preset_levels: no rows")
        return 2
    rms = sorted(r[4] for r in rows)
    med = rms[len(rms) // 2]
    base = lv[100]
    have = current_levels()
    per_engine = {}
    reached, capped = 0, []
    for e, i, eng, name, r, pk in rows:
        need_db = med - r
        arr = eng_array_name(eng)
        cur = 100
        if arr in have and i < len(have[arr]):
            cur = have[arr][i]
        cur_db = 20.0 * __import__("math").log10(lv[cur] / base) if lv[cur] else -200.0
        target = cur_db + need_db
        best, best_err = cur, 1e9
        for L in range(1, 128):
            db = 20.0 * __import__("math").log10(lv[L] / base) if lv[L] else -200.0
            err = abs(db - target)
            if err < best_err:
                best, best_err = L, err
        got = 20.0 * __import__("math").log10(lv[best] / base) if lv[best] else -200.0
        if abs((got - cur_db) - need_db) > 1.0:
            capped.append((eng, name, need_db, got))
        else:
            reached += 1
        per_engine.setdefault(e, {})[i] = best
    out = ['/* SPDX-License-Identifier: GPL-3.0-only',
           ' * Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments */',
           '/* GENERATED by tools/gen_preset_levels.py from a measured render of every factory preset',
           ' * (tests/preset_levels). Do not edit by hand: measure again and regenerate.',
           ' *',
           ' * A sound carries its own level, as a patch does. Before this table the fader was whatever the',
           ' * track had, so changing preset jumped by up to 27.6 dB -- the spread the measurement found.',
           ' * The values are LEVEL_Q12 indices (0..127), the same table the mixer multiplies by. */',
           '']
    guard = set()
    e_name = {}
    for e, i, eng, name, r, pk in rows:
        e_name[e] = eng
    for e, m in per_engine.items():
        n = max(m.keys()) + 1
        vals = [m.get(i, 100) for i in range(n)]
        arr = eng_array_name(e_name[e])
        guard.add(eng)
        out.append("static const uint8_t %s[%d] = {" % (arr, n))
        for k in range(0, n, 16):
            out.append("    " + ", ".join("%3d" % v for v in vals[k:k + 16]) + ",")
        out.append("};")
        out.append("")
    out.append("/* the level preset `pi` of engine `e` loads with (100: the fader's own, untouched) */")
    out.append("uint8_t preset_level_of(uint32_t e, uint32_t pi)")
    out.append("{")
    out.append("    switch (e) {")
    e_name = {}
    for e, i, eng, name, r, pk in rows:
        e_name[e] = eng
    for e in sorted(per_engine):
        n = max(per_engine[e].keys()) + 1
        out.append("    case %d: return pi < %du ? %s[pi] : 100u;   /* %s */" %
                   (e, n, eng_array_name(e_name[e]), e_name[e]))
    out.append("    default: return 100u;")
    out.append("    }")
    out.append("}")
    open("firmware/src/preset_level.c", "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("gen_preset_levels: median %+.1f dBFS, %u of %u presets set by the fader, %u out of reach"
          % (med, reached, len(rows), len(capped)))
    for eng, name, need, got in capped:
        print("   out of reach: %-9s %-14s needs %+5.1f dB, the level gives %+5.1f" % (eng, name, need, got))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
