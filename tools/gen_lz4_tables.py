"""(FASE 5c) THE TWO TABLES THAT LZ4 CAN GIVE BACK, FROM THE COMPILER'S OWN BYTES.

XIP is 1 644 B short of its floor and four of the five candidate tables carry pointers, so they cannot be
copied out of a compressed blob at all (a pointer in .rodata is a relocation: the bytes in the object file are
the *linked* address, not the address the .bss copy will have -- the same reason TP could not be compressed).
That leaves the two that are pure bytes:

    PRESET_NAMES  3 142 B -> 2 445 B   (the factory presets' text, one blob, FASE 1/10)
    FM6_ROMBANK   1 408 B ->   956 B   (the built-in GW-1 keys, 11 banks x 128 B)

Both are read-only tables that nothing writes, and both are only ever read through PRESET_NAMES / FM6_ROMBANK
(PR_NAME() adds an offset; fvb_rom_read copies a bank). This tool reads them from the object of the *packing*
pass (build/preset_src.o, -DQG_PRESET_SOURCE=1, the same object gen_preset_pack.py uses), checks that neither
section has a single relocation -- that check is what makes the memcpy into .bss legal -- compresses them with
tools/lz4blk.py, decompresses its own output and compares it byte for byte with the compiler's, and writes
build/gen/lz4_tables.h. The firmware's lz4_tables_init() (lz4_tab.c) rebuilds both in .bss at boot, so the
readers do not know this file exists. A table that would not survive the round trip stops the build.

  gen_lz4_tables.py OBJ DESTDIR
"""
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lz4blk                                                       # noqa: E402

TABLES = [("PRESET_NAMES", "LZ4_PN"), ("FM6_ROMBANK", "LZ4_FM6")]


def sections(obj):
    out = subprocess.run(["readelf", "-SW", str(obj)], capture_output=True, text=True)
    if out.returncode:
        raise SystemExit("gen_lz4_tables: readelf failed: " + out.stderr.strip())
    found = {}
    for line in out.stdout.splitlines():
        f = line.replace("]", "").split()
        if len(f) >= 6 and f[1].startswith(".rodata."):
            found[f[1][len(".rodata."):]] = (int(f[4], 16), int(f[5], 16))
    return found


def relocations(obj):
    out = subprocess.run(["readelf", "-rW", str(obj)], capture_output=True, text=True)
    return {line.split("'")[1] for line in out.stdout.splitlines()
            if line.startswith("Relocation section") and "'" in line}


def main(argv):
    if len(argv) != 3:
        raise SystemExit(__doc__)
    obj, dest = Path(argv[1]), Path(argv[2])
    data = obj.read_bytes()
    secs, rels = sections(obj), relocations(obj)
    blobs, sizes, meta = [], {}, []
    for sym, tag in TABLES:
        if sym not in secs:
            raise SystemExit(f"gen_lz4_tables: {sym} is not in {obj}")
        if f".rela.rodata.{sym}" in rels:
            raise SystemExit(f"gen_lz4_tables: {sym} carries a relocation: it has a pointer in it and a "
                             f"compressed copy could not be rebuilt by memcpy")
        off, size = secs[sym]
        raw = data[off:off + size]
        packed = lz4blk.compress(raw)
        if lz4blk.decompress(packed) != raw:                  # the blob has to reproduce the compiler's bytes
            raise SystemExit(f"gen_lz4_tables: {sym} does not survive the round trip")
        sizes[tag + "_LEN"] = size
        sizes[tag + "_CLEN"] = len(packed)
        meta.append((sym, size, len(packed)))
        blobs.append(packed)
    total = sum(len(b) for b in blobs)
    lines = ["/* generated by tools/gen_lz4_tables.py from build/preset_src.o -- do not edit */",
             "/* LZ4 block format (tools/lz4blk.py), rebuilt in .bss at boot by lz4_tables_init() (lz4_tab.c):"]
    for sym, size, clen in meta:
        lines.append(f" *   {sym:12s} {size:5d} B -> {clen:5d} B of XIP")
    lines.append(" */")
    lines.append(f"#define LZ4_BLOB_LEN {total}")
    for k in sorted(sizes):
        lines.append(f"#define {k} {sizes[k]}")
    lines.append(f"static const uint8_t LZ4_TAB_BLOB[LZ4_BLOB_LEN] = {{")
    flat = b"".join(blobs)
    for i in range(0, len(flat), 16):
        lines.append("    " + " ".join(f"0x{b:02X}," for b in flat[i:i + 16]))
    lines.append("};")
    (dest / "lz4_tables.h").write_text("\n".join(lines) + "\n")
    print("gen_lz4_tables: " + ", ".join(f"{s} {z}->{c}" for s, z, c in meta)
          + f" ({sum(z - c for _, z, c in meta)} B of XIP before the decoder)")


if __name__ == "__main__":
    main(sys.argv)
